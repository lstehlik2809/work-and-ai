import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';

const base=process.env.TEST_URL||'http://127.0.0.1:4173/work-and-ai/';
const out=resolve(process.env.OUTPUT_DIR||'verification/local/result-limit');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const report={base,date:new Date().toISOString(),checks:[],errors:[]};
page.on('pageerror',error=>report.errors.push(String(error)));
const limit=page.getByRole('combobox',{name:'Show top'});
const cards=page.locator('.candidate');
const codes=()=>cards.locator('.code').allTextContents();
try{
 await page.goto(base);
 assert.equal(await limit.inputValue(),'5');
 await page.getByRole('searchbox',{name:'Job title'}).fill('electrical');
 await cards.first().waitFor();
 const firstFive=await codes();assert.equal(firstFive.length,5);
 assert.match(await page.locator('#title-status').innerText(),/5 suggestions/);
 await limit.selectOption('1');assert.deepEqual(await codes(),firstFive.slice(0,1));
 await limit.selectOption('10');const all=await codes();assert.equal(all.length,8);
 assert.deepEqual(all.slice(0,5),firstFive);
 await limit.selectOption('5');assert.deepEqual(await codes(),firstFive);
 report.checks.push('Default five title matches; 1/5/10 controls preserve order and show fewer when only eight qualify');
 await cards.first().click();
 await page.getByRole('button',{name:'Add to comparison',exact:true}).click();
 const confirmed=await page.locator('#occupation-heading').innerText();
 await page.getByRole('button',{name:/describe your work/i}).click();
 const fixtures=JSON.parse(await readFile('data/evaluation/matching-v2-development.json','utf8'));
 await page.getByRole('textbox',{name:'A few specific responsibilities, in English'}).fill(fixtures.cases.find(f=>f.id==='U01').input);
 await page.getByRole('button',{name:'Search by meaning',exact:true}).click();
 await page.locator('.refine [role="status"]').filter({hasText:'Enhanced matching finished'}).waitFor({timeout:120000});
 assert.deepEqual((await codes()).map(text=>text.match(/\d{2}-\d{4}/)[0]),['15-2051','19-3032']);
 await limit.selectOption('1');assert.equal(await cards.count(),1);
 await limit.selectOption('10');assert.equal(await cards.count(),2);
 assert.match(await page.locator('.refine [role="status"]').innerText(),/Enhanced matching finished/);
 assert.equal(await page.locator('#occupation-heading').innerText(),confirmed);
 assert.equal(await page.locator('.comparison thead th').count(),2);
 report.checks.push('Description limit updates completed results immediately and preserves confirmed occupation/comparison');
 await page.getByRole('button',{name:'Clear results',exact:true}).click();
 assert.equal(await limit.inputValue(),'10');assert.equal(await cards.count(),0);
 await page.getByRole('searchbox',{name:'Job title'}).fill('qzxv blorpt 739');
 await page.locator('#title-status').filter({hasText:'No close matches'}).waitFor();
 assert.equal(await cards.count(),0);
 report.checks.push('Clear results preserves preference; a larger limit does not fill no-match results');
 await page.setViewportSize({width:390,height:844});
 await limit.scrollIntoViewIfNeeded();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert(await limit.isVisible());
 await mkdir(out,{recursive:true});
 await page.screenshot({path:resolve(out,'mobile.png')});
 assert.deepEqual(report.errors,[]);report.status='PASS';
 console.log(JSON.stringify(report));
}finally{
 await mkdir(out,{recursive:true});
 await writeFile(resolve(out,'report.json'),JSON.stringify(report,null,2)+'\n');
 await browser.close();
}
