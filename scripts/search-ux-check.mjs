import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';

const base=process.env.TEST_URL||'http://127.0.0.1:4173/work-and-ai/';
const out=resolve(process.env.OUTPUT_DIR||'verification/local/search-ux');
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const checks=[],errors=[],requests=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('request',request=>requests.push(request.url()));
const check=name=>{checks.push(name);console.log(name);};
const title=page.getByRole('searchbox',{name:'Job title'});
const status=page.locator('.search-section [role="status"]').first();
const describe=()=>page.getByRole('button',{name:/describe your work/i});
const close=()=>page.getByRole('button',{name:/close/i});
const responsibilities=()=>page.getByRole('textbox',{name:'A few specific responsibilities, in English'});
let releaseImport;
try{
 await page.goto(base);
 await page.waitForFunction(()=>document.querySelector('#job-title')?.disabled===false);
 assert.equal(await page.getByRole('button',{name:/Find occupation/}).count(),0);
 await page.clock.install();
 await page.clock.pauseAt(new Date(Date.now()+1000));
 await title.fill('database');
 assert.match(await status.innerText(),/searching/i);
 assert.equal(await page.locator('.candidate').count(),0);
 await page.clock.runFor(1000);
 await page.getByRole('button',{name:/^Database Administrators BLS/}).waitFor();
 await page.getByRole('button',{name:/^Database Architects BLS/}).waitFor();
 assert.match(await status.innerText(),/2 suggestions/i);
 check('Automatic single-word database search exposes activity and two relevant results');
 await title.fill('database eng');
 assert.match(await status.innerText(),/searching/i);
 assert.equal(await page.locator('.candidate').count(),0);
 await page.clock.runFor(1000);
 assert.equal(await page.locator('.candidate').count(),2);
 check('Incomplete multiword title matches; old candidates disappear during debounce');
 await title.fill('qzxv blorpt 739');
 await page.clock.runFor(1000);
 assert.match(await status.innerText(),/no .*match|no .*found/i);
 assert.match(await status.innerText(),/describe your work/i);
 assert.equal(await page.locator('.candidate').count(),0);
 assert.equal(await describe().count(),1);
 await page.screenshot({path:resolve(out,'no-results.png'),fullPage:true});
 check('No results is explicit and offers one description action');
 await title.fill('engineer');
 await page.clock.runFor(1000);
 assert.match(await status.innerText(),/specific|specialty|field|different occupations/i);
 assert.equal(await page.locator('.candidate').count(),0);
 await title.fill('');
 await page.clock.runFor(1000);
 assert.doesNotMatch(await status.innerText(),/searching|no .*match/i);
 check('Broad titles request clarification; clearing restores idle feedback');
 await describe().click();
 await responsibilities().fill('I maintain databases and manage database backups.');
 await close().click();
 assert.equal(await page.locator('.refine').count(),0);
 await page.clock.runFor(1);
 assert(await describe().evaluate(el=>el===document.activeElement));
 await describe().click();
 assert.equal(await responsibilities().inputValue(),'I maintain databases and manage database backups.');
 check('Close is available before searching, returns focus, and preserves description draft');
 await page.clock.resume();
 let importSeen;
 const seen=new Promise(resolve=>{importSeen=resolve;});
 const release=new Promise(resolve=>{releaseImport=resolve;});
 await page.route(/\/(?:assets\/client-[^/]+\.js|src\/semantic\/client\.ts)(?:\?|$)/,async route=>{
  importSeen();await release;await route.continue();
 });
 await page.getByRole('button',{name:'Search by meaning',exact:true}).click();
 await Promise.race([seen,new Promise((_,reject)=>setTimeout(()=>reject(Error('Dynamic import was not intercepted')),10000))]);
 await close().click();
 releaseImport();
 await page.waitForLoadState('networkidle');
 assert.equal(await page.locator('.refine').count(),0);
 assert(!requests.some(url=>/\/models\/|\/runtime\/|\/semantic\/metadata|\/assets\/worker-/.test(url)));
 await title.fill('database');
 await page.getByRole('button',{name:/^Database Administrators BLS/}).waitFor();
 check('Closing during delayed matcher import prevents background matching and preserves title search');
 await page.setViewportSize({width:390,height:844});
 await describe().click();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await close().scrollIntoViewIfNeeded();
 const bounds=await close().boundingBox();
 assert(bounds&&bounds.x>=0&&bounds.x+bounds.width<=390);
 await page.screenshot({path:resolve(out,'mobile-description.png'),fullPage:true});
 await close().click();
 check('390px description panel has no horizontal overflow and an accessible close action');
 await page.goto(base+'diagnostics.html');
 await page.getByRole('combobox',{name:'App failure scenario'}).selectOption('hang');
 await title.fill('registered nurse');
 await page.getByRole('button',{name:/^Registered Nurses BLS/}).click();
 await page.getByRole('button',{name:'Add to comparison',exact:true}).click();
 await describe().click();
 await responsibilities().fill('I maintain databases and manage database backups.');
 await page.getByRole('button',{name:'Search by meaning',exact:true}).click();
 await page.getByRole('button',{name:'Matching…',exact:true}).waitFor();
 await close().click();
 await title.fill('database');
 await page.getByRole('button',{name:/^Database Administrators BLS/}).waitFor();
 await page.waitForTimeout(1800); // Exceed the diagnostic worker's 1.5s timeout.
 assert.equal(await page.getByRole('alert').count(),0);
 assert.equal(await page.locator('.refine').count(),0);
 assert.equal(await page.locator('.candidate').count(),2);
 assert.equal(await page.locator('.comparison thead th').count(),2);
 assert.match(await page.locator('#occupation-heading').innerText(),/Registered nurses/i);
 await describe().click();
 assert.equal(await responsibilities().inputValue(),'I maintain databases and manage database backups.');
 assert.equal(await page.locator('.refine [role="status"]').innerText(),'');
 check('Close cancels a running worker without late errors or changes to confirmed selection/comparison');
 assert.deepEqual(errors,[]);
}finally{
 releaseImport?.();
 await writeFile(resolve(out,'report.json'),JSON.stringify({date:new Date().toISOString(),base,checks,errors},null,2)+'\n');
 await browser.close();
}
